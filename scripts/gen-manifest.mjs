// Regenerate src/lib/screenshots-manifest.ts from the files in
// public/screenshots. Run this after capturing new screenshots so the docs know
// which localized captures exist (see src/lib/screenshots.ts for why a manifest
// is used instead of a runtime filesystem check).
//
//   node scripts/gen-manifest.mjs

import fs from "node:fs";
import path from "node:path";

const DIR = path.resolve("public/screenshots");
const OUT = path.resolve("src/lib/screenshots-manifest.ts");

const keys = fs
  .readdirSync(DIR)
  .filter((f) => f.endsWith(".jpg"))
  .map((f) => f.replace(/\.jpg$/, ""))
  .sort();

const body =
  `// AUTO-GENERATED by scripts/screenshots-local.mjs and scripts/gen-manifest.mjs.\n` +
  `// Lists every <name>-<lang> screenshot present in public/screenshots, so the\n` +
  `// shot() helper can resolve the right language at build time without touching\n` +
  `// the filesystem (the Cloudflare SSR bundle runs in an isolated sandbox).\n` +
  `export const AVAILABLE: ReadonlySet<string> = new Set([\n` +
  keys.map((k) => `  "${k}",`).join("\n") +
  `\n]);\n`;

fs.writeFileSync(OUT, body);
console.log(`Wrote ${path.relative(process.cwd(), OUT)} with ${keys.length} entries`);
